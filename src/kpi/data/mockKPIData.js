export const KPI_DATA_VERSION = 'v15_rejection_and_full_year_months';

// Tự động đồng bộ chuẩn hóa dữ liệu init theo yêu cầu mới nhất (xóa Vũ Mạnh Hùng, reset luồng phê duyệt Q3)
if (typeof window !== 'undefined' && window.localStorage) {
  try {
    // Luôn dọn sạch tài khoản Vũ Mạnh Hùng khỏi localStorage nếu còn lưu
    const rawUsers = window.localStorage.getItem('kpi_users');
    if (rawUsers) {
      try {
        const parsedUsers = JSON.parse(rawUsers);
        const filteredUsers = parsedUsers.filter(
          (u) => u.id !== 'user_depthead_02' && u.username !== 'hung.vumanh' && u.name !== 'Vũ Mạnh Hùng'
        );
        window.localStorage.setItem('kpi_users', JSON.stringify(filteredUsers));
      } catch {}
    }

    const currentAuthUser = window.localStorage.getItem('kpi_auth_user');
    if (currentAuthUser) {
      try {
        const parsedAuth = JSON.parse(currentAuthUser);
        if (parsedAuth.id === 'user_depthead_02' || parsedAuth.username === 'hung.vumanh' || parsedAuth.name === 'Vũ Mạnh Hùng') {
          window.localStorage.removeItem('kpi_auth_user');
        } else if (parsedAuth.name === 'Cán bộ 2' || (parsedAuth.title && parsedAuth.title.toLowerCase().includes('tccb'))) {
          parsedAuth.managedDeptId = 'DEP_TCCB';
          parsedAuth.deptId = 'DEP_TCCB';
          parsedAuth.department = 'Phòng Tổ chức cán bộ';
          window.localStorage.setItem('kpi_auth_user', JSON.stringify(parsedAuth));
        }
      } catch {}
    }

    // Luôn đảm bảo OKRs lưu trong localStorage có gán mã phòng ban chuẩn xác
    const rawOkrs = window.localStorage.getItem('kpi_okr_list');
    if (rawOkrs) {
      try {
        const parsedOkrs = JSON.parse(rawOkrs);
        let okrsChanged = false;
        parsedOkrs.forEach((o) => {
          if (
            o.code === 'OKR_09' ||
            o.code === 'OKR_02' ||
            o.code === 'OKR_03' ||
            o.code === 'OKR_06' ||
            (o.owner && (o.owner.includes('Lê Hoàng Long') || o.owner.includes('Trần Thị Mai'))) ||
            o.createdBy === 'user_leadership_01'
          ) {
            if (o.deptId !== 'DEP_TCD') {
              o.deptId = 'DEP_TCD';
              o.department = 'Phòng Tổ chức đảng - Đảng viên';
              okrsChanged = true;
            }
          } else if (
            o.code === 'OKR_01' ||
            o.code === 'OKR_04' ||
            (o.owner && o.owner.includes('Bảo vệ chính trị'))
          ) {
            if (o.deptId !== 'DEP_BV') {
              o.deptId = 'DEP_BV';
              o.department = 'Phòng Bảo vệ chính trị nội bộ';
              okrsChanged = true;
            }
          } else if (
            o.code === 'OKR_05' ||
            (o.owner && (o.owner.includes('Tổ chức cán bộ') || o.owner.includes('Cán bộ 2'))) ||
            (o.title && o.title.toLowerCase().includes('tccb'))
          ) {
            if (o.deptId !== 'DEP_TCCB') {
              o.deptId = 'DEP_TCCB';
              o.department = 'Phòng Tổ chức cán bộ';
              okrsChanged = true;
            }
          }
        });
        if (okrsChanged) {
          window.localStorage.setItem('kpi_okr_list', JSON.stringify(parsedOkrs));
        }
      } catch {}
    }

    const currentVersion = window.localStorage.getItem('kpi_data_version');
    if (currentVersion !== KPI_DATA_VERSION) {
      window.localStorage.setItem('kpi_departments', JSON.stringify(INITIAL_DEPARTMENTS));
      window.localStorage.setItem('kpi_okr_list', JSON.stringify(INITIAL_OKRS));

      // Bảo toàn các nhiệm vụ do người dùng tự tạo trong phiên làm việc
      try {
        const rawTasks = window.localStorage.getItem('kpi_assigned_tasks');
        if (rawTasks) {
          const parsed = JSON.parse(rawTasks);
          if (Array.isArray(parsed)) {
            const initialIds = new Set(INITIAL_ASSIGNED_TASKS.map((t) => t.id));
            const userCustomTasks = parsed.filter((t) => !initialIds.has(t.id));
            window.localStorage.setItem('kpi_assigned_tasks', JSON.stringify([...userCustomTasks, ...INITIAL_ASSIGNED_TASKS]));
          } else {
            window.localStorage.setItem('kpi_assigned_tasks', JSON.stringify(INITIAL_ASSIGNED_TASKS));
          }
        } else {
          window.localStorage.setItem('kpi_assigned_tasks', JSON.stringify(INITIAL_ASSIGNED_TASKS));
        }
      } catch {
        window.localStorage.setItem('kpi_assigned_tasks', JSON.stringify(INITIAL_ASSIGNED_TASKS));
      }

      // Bảo toàn cán bộ do Super Admin tạo thêm
      try {
        const rawStaffs = window.localStorage.getItem('kpi_staffs');
        if (rawStaffs) {
          const parsed = JSON.parse(rawStaffs);
          if (Array.isArray(parsed)) {
            const initialStaffIds = new Set(INITIAL_STAFFS.map((s) => s.id));
            const userCustomStaffs = parsed.filter((s) => !initialStaffIds.has(s.id));
            window.localStorage.setItem('kpi_staffs', JSON.stringify([...INITIAL_STAFFS, ...userCustomStaffs]));
          } else {
            window.localStorage.setItem('kpi_staffs', JSON.stringify(INITIAL_STAFFS));
          }
        } else {
          window.localStorage.setItem('kpi_staffs', JSON.stringify(INITIAL_STAFFS));
        }
      } catch {
        window.localStorage.setItem('kpi_staffs', JSON.stringify(INITIAL_STAFFS));
      }

      window.localStorage.setItem('kpi_evaluations', JSON.stringify(INITIAL_EVALUATIONS));
      window.localStorage.setItem('kpi_agency_approval', JSON.stringify(INITIAL_AGENCY_APPROVALS));
      window.localStorage.setItem('kpi_data_version', KPI_DATA_VERSION);
    }
  } catch (e) {
    console.error('Lỗi khởi tạo đồng bộ dữ liệu KPI:', e);
  }
}

